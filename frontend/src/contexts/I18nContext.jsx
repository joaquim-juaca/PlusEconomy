const I18nCtx = createContext(null);

export function I18nProvider({ children }) {
  const [lang, setLang] = useState(() => localStorage.getItem("pe_lang") || "pt");
  useEffect(() => {
    localStorage.setItem("pe_lang", lang);
    document.documentElement.lang = lang;
  }, [lang]);
  const t = (key) => {
    const val = key.split(".").reduce((o, k) => (o ? o[k] : undefined), dict[lang]);
    return val ?? key;
  };
  const tCat = (cat) => dict[lang].categories[cat] || cat;
  const setLanguage = (l) => setLang(l);
  return (
    <I18nCtx.Provider value={{ lang, t, tCat, setLanguage }}>{children}</I18nCtx.Provider>
  );
}

export const useI18n = () => useContext(I18nCtx);

